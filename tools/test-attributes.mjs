// 聚焦回归：使用实际引擎函数验证扫描根属性和上下文优先级。
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code=await readFile(new URL('../src/content.js',import.meta.url),'utf8');
const lookupCode=code.slice(code.indexOf('  function pickTerm('),code.indexOf('  // ================= 页面改写'));
const scanCode=code.slice(code.indexOf('  function translateAttribute('),code.indexOf('  // ================= 动态内容监听'));
let writes=0;
const makeElement=(attrs={},skip=false)=>({nodeType:1,isConnected:true,skip,attrs:{...attrs},getAttribute(k){return this.attrs[k]??null},setAttribute(k,v){writes++;this.attrs[k]=v},querySelectorAll(){return this.children||[]}});
const context={Node:{ELEMENT_NODE:1,TEXT_NODE:3},NodeFilter:{SHOW_TEXT:4,FILTER_ACCEPT:1,FILTER_REJECT:2},document:{createTreeWalker(){return {nextNode(){return null}}}},normalize:s=>s.trim(),EMOJI_PREFIX:/^(nevermatches)(.*)$/,isSkipped:n=>n.skip,translateText(){},index:{page:new Map([['Sticky','固定']]),global:new Map([['Sticky','置顶'],['Search','搜索']]),attrs:new Map([['Search','搜索框']]),regex:[]}};
context.activeDictionary=null;context.translatedAttributes=new WeakMap();
context.UI_TEXT_SCOPE='button,label,th';
vm.createContext(context);vm.runInContext(lookupCode+scanCode,context);
const root=makeElement({title:'Sticky','aria-label':'Search',placeholder:'Unknown'});
context.scan(root);assert.equal(root.attrs.title,'固定');assert.equal(root.attrs['aria-label'],'搜索框');assert.equal(root.attrs.placeholder,'Unknown');
const previous=writes;context.scan(root);assert.equal(writes,previous,'相同译文不得重复写入');
root.attrs.title='Search';context.scan(root);assert.equal(root.attrs.title,'搜索框','动态根属性必须重译');
const excluded=makeElement({title:'Search'},true);context.scan(excluded);assert.equal(excluded.attrs.title,'Search','跳过区不得改写');
const child=makeElement({title:'Sticky'});root.children=[child];context.scan(root);assert.equal(child.attrs.title,'固定','后代属性仍应翻译');
context.index.page.clear();assert.equal(context.lookup('Sticky'),'置顶','页面未命中才退回通用词典');assert.equal(context.lookup('Unlisted game name'),null);
console.log('PASS: 根/后代属性、动态重译、跳过区、未知文本保护、无变化跳过及页面优先级');
context.index.contexts=[{selector:'.setting',attribute:'title',terms:new Map([['Sticky','吸附']])},{selector:'[bad',terms:new Map()}];
root.closest=s=>{if(s==='[bad')throw Error('invalid selector');return s==='.setting'?root:null};
root.attrs.title='Sticky';context.scan(root);assert.equal(root.attrs.title,'吸附','控件属性上下文优先于页面词典');
context.index.contexts=[];context.scan(root);assert.equal(root.attrs.title,'置顶','从原文重新匹配而非匹配旧译文');
context.index.global.clear();context.scan(root);assert.equal(root.attrs.title,'Sticky','规则消失时恢复原文');
assert.equal(context.lookup('Unknown',root),null,'未知文本保留');
context.index.global.set('Search','搜索');
const plain={closest:()=>null};assert.equal(context.lookup('Search',plain),null,'普通内容不使用通用词条');
const button={closest:s=>s===context.UI_TEXT_SCOPE?button:null};assert.equal(context.lookup('Search',button),'搜索','界面控件仍命中');
console.log('PASS: 控件上下文优先、原文重匹配及失效规则恢复');
